"""Step 3: write ``docs/03_cleaning_report.md`` from the cleaning outputs.

Every number in the report is computed here from ``funnel.json`` and the clean
tables, so the report can never drift from the data.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import duckdb

from agent_tips.cleaning.schema import STEPS, TRIES, markdown_dictionary
from agent_tips.config import Config

# Counts found during exploration (2026-10-19), used as a consistency check.
EXPECTED: list[tuple[str, str, int]] = [
    ("older_ai: all tries", "dataset = 'older_ai'", 80036),
    ("older_ai: in scope (70B)", "dataset = 'older_ai' AND in_scope", 74792),
    ("older_ai: in scope, same input", "dataset = 'older_ai' AND in_scope AND same_input", 73738),
    ("older_ai: in scope, dated", "dataset = 'older_ai' AND in_scope AND dated", 64274),
    ("older_ai: issues (70B)", "dataset = 'older_ai' AND in_scope", -3591),
    ("newer_ai_nebius: all tries", "dataset = 'newer_ai_nebius'", 67074),
    ("newer_ai_nebius: same input", "dataset = 'newer_ai_nebius' AND same_input", 67049),
    ("newer_ai_nvidia: all tries", "dataset = 'newer_ai_nvidia'", 254933),
]

DATASET_NAMES = {
    "older_ai": "Older AI (nebius/SWE-agent-trajectories)",
    "newer_ai_nebius": "Newer AI, Nebius (Qwen3-Coder in OpenHands)",
    "newer_ai_nvidia": "Newer AIs, NVIDIA (7 subsets of Open-SWE-Traces)",
}


def _fmt(n: Any) -> str:
    return "—" if n is None else (f"{n:,}" if isinstance(n, int) else str(n))


def _funnel_tables(funnel: list[dict[str, Any]]) -> str:
    out: list[str] = []
    for ds, title in DATASET_NAMES.items():
        rows = [r for r in funnel if r["dataset"] == ds]
        if not rows:
            continue
        out += [
            f"### {title}",
            "",
            "| Stage | Tries | Issues | Removed | Resolved rate |",
            "| --- | ---: | ---: | ---: | ---: |",
        ]
        for r in rows:
            rate = "—" if r["resolved_rate"] is None else f"{r['resolved_rate']:.1%}"
            out.append(
                f"| {r['stage']} | {_fmt(r['tries'])} | {_fmt(r['issues'])} | "
                f"{_fmt(r['removed'])} | {rate} |"
            )
        out.append("")
    return "\n".join(out)


def _checks(con: duckdb.DuckDBPyConnection) -> tuple[str, bool]:
    lines = ["| Check | Expected (exploration) | Found | Match |", "| --- | ---: | ---: | :---: |"]
    ok_all = True
    for label, cond, expected in EXPECTED:
        if expected < 0:  # negative = count distinct issues
            row = con.execute(f"SELECT count(DISTINCT issue_id) FROM tries WHERE {cond}").fetchone()
            expected = -expected
        else:
            row = con.execute(f"SELECT count(*) FROM tries WHERE {cond}").fetchone()
        found = int(row[0]) if row else 0
        ok = found == expected
        ok_all &= ok
        lines.append(f"| {label} | {expected:,} | {found:,} | {'✅' if ok else '❌'} |")
    return "\n".join(lines), ok_all


def _per_subset(con: duckdb.DuckDBPyConnection) -> str:
    df = con.execute(
        """
        SELECT dataset, subset, count(*) AS tries, count(DISTINCT issue_id) AS issues,
          quantile_cont(k, 0.5) AS med_tries_per_issue,
          avg(resolved) AS resolved_rate, avg(n_steps) AS mean_steps
        FROM (SELECT *, count(*) OVER (PARTITION BY issue_key) AS k FROM tries
              WHERE in_scope AND same_input AND outcome_known)
        GROUP BY 1, 2 ORDER BY 1, 2
        """
    ).df()
    lines = [
        "| Dataset | Subset | Tries | Issues | Median tries per issue | Resolved | Mean steps |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for r in df.itertuples():
        lines.append(
            f"| {r.dataset} | {r.subset} | {r.tries:,} | {r.issues:,} | {r.med_tries_per_issue:.0f} "
            f"| {r.resolved_rate:.1%} | {r.mean_steps:.1f} |"
        )
    return "\n".join(lines)


def build(cfg: Config, out: Path | None = None) -> Path:
    """Write the cleaning report and return its path."""
    summary = json.loads((cfg.path("results") / "funnel.json").read_text(encoding="utf-8"))
    con = duckdb.connect()
    tries = (cfg.path("processed") / "tries.parquet").as_posix()
    con.execute(f"CREATE VIEW tries AS SELECT * FROM read_parquet('{tries}')")
    checks, ok = _checks(con)
    steps = summary["steps"]
    steps_lines = "\n".join(f"| {k} | {v:,} |" for k, v in steps.items())
    text = f"""# Step 3: Cleaning Report

*Generated by `agent-tips clean` from `outputs/results/funnel.json` and `data/processed/`. Do not edit by hand.*

## In plain words

- We turned the three AI-recording datasets into **two tables with the same columns**:
  - one row per **try** ({sum(r["tries"] for r in summary["funnel"] if r["stage"].startswith("All")):,} tries);
  - one row per **step** the AI took ({sum(steps.values()):,} steps).
- **No rows were thrown away.** Instead, each try carries yes/no flags (in scope, same issue text, outcome known, dated), and each analysis picks the rows it needs. The tables below show how many tries pass each filter, like a funnel.
- **Consistency check:** {"every count matches our earlier exploration exactly." if ok else "some counts differ from the exploration; see the check table."}
- **Duplicate try IDs:** {summary["duplicate_try_ids"]} (must be 0).

## Funnels

{_funnel_tables(summary["funnel"])}
## Consistency with the exploratory analysis

{checks}

## Analysis-ready tries per subset

Tries that are in scope, have the same issue text, and have a known outcome:

{_per_subset(con)}

## Steps table

| Dataset | Steps (AI actions) |
| --- | ---: |
{steps_lines}

Commands are truncated to 500 characters and observations to their first 300 characters. Full text stays in `data/raw/` for later checks.

## Cleaning rules

1. **Older AI:** only `swe-agent-llama-70b` is in scope. The 8B and 405B tries are kept but flagged out of scope.
2. **Same input:** for every issue (within one AI configuration), the most common issue text is the reference. Tries that saw a different text are flagged `same_input = false`.
3. **Outcome:** NVIDIA tries with `resolved = -1` are flagged `outcome_known = false`.
4. **Dating (older AI):** the evaluation time is read from the eval log. Tries with no eval log, which are always unresolved because they produced no patch, are flagged `dated = false`.
5. **Batches (older AI):** day, 6-hour and hour windows, plus "bursts" that start after a 60-minute or 10-minute pause in evaluation times within an issue. These serve as proxies for the model version.
6. **Languages:** NVIDIA's `js`/`ts` are normalized to `javascript`/`typescript`.

## Data dictionary: `tries`

{markdown_dictionary(TRIES)}

## Data dictionary: `steps`

{markdown_dictionary(STEPS)}
"""
    path = out or cfg.root / "docs" / "03_cleaning_report.md"
    path.write_text(text, encoding="utf-8")
    return path
