"""Step 6 (one-try study): modelling.

1. The **answer key** for every qualifying comparison (many-tries answer with
   its bootstrap CI and noise floor).
2. A **go/no-go** check: on the pilot's four comparisons ("test first", four
   NVIDIA setups) the methods must repeat the pilot's pattern: the error
   falls from the simple comparison to report-text ML to other-AI ML.
3. The report ``docs/one_try/06_modelling.md``.

The methods themselves are in :mod:`agent_tips.onetry.corrections`; their
tests on made-up data with a known answer are ``tests/test_onetry_corrections.py``.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from threadpoolctl import threadpool_limits

from agent_tips.config import Config
from agent_tips.onetry import corrections as cr
from agent_tips.onetry import data
from agent_tips.onetry.features import tokenize
from agent_tips.onetry.simulate import answer_key, one_try_copy

PILOT = [
    "sweagent/qwen36_27b/scale-swe|test_first",
    "sweagent/qwen35_122b/swe-rebench-v2|test_first",
    "openhands/qwen35_122b/swe-rebench-v2|test_first",
    "sweagent/minimax_m25/swe-rebench-v2|test_first",
]
SYNTHETIC_TESTS = [
    ("Simple comparison is fooled by the easy-bug trap", "test_simple_comparison_is_fooled"),
    ("ML on an uninformative report stays fooled", "test_ml_on_report_text_alone_stays_fooled"),
    (
        "ML with a clear difficulty clue finds a zero effect",
        "test_ml_with_other_ai_information_finds_zero",
    ),
    (
        "ML with a clear clue finds a +10-point effect (rungs 5 and 6)",
        "test_ml_with_other_ai_information_finds_a_real_effect",
    ),
    (
        "AIPW check finds a +10-point effect when both choices are likely",
        "test_aipw_check_finds_a_real_effect_with_fair_overlap",
    ),
    (
        "The answer key finds the true effect despite the trap",
        "test_answer_key_finds_the_true_effect_despite_the_trap",
    ),
    (
        "The cached text model gives identical numbers",
        "test_pretokenized_text_model_gives_identical_numbers",
    ),
]


def answer_keys(s: data.StudyData, reps: int, log: Callable[[str], None] = print) -> pd.DataFrame:
    """Answer key of every qualifying comparison."""
    rows = []
    for c in s.comparisons:
        k = answer_key(c, s.tries, reps=reps)
        rows.append(
            {
                "cid": c.cid,
                "dataset": c.dataset,
                "setup": c.setup,
                "behaviour": c.behaviour,
                "kind": "true experiment" if c.experiment else "mid-run",
                "estimate": k.estimate,
                "ci_lo": k.ci_lo,
                "ci_hi": k.ci_hi,
                "noise_floor": k.noise_floor,
                "conclusion": k.conclusion,
                "key_bugs": k.key_bugs,
                "key_groups": k.key_groups,
            }
        )
    log(f"answer keys: {len(rows)} comparisons")
    return pd.DataFrame(rows)


def go_no_go(s: data.StudyData, keys: pd.DataFrame, draws: int = 5) -> pd.DataFrame:
    """Rungs 0, 2, 4, 5 on the pilot's comparisons (absolute error vs the answer key)."""
    rows = []
    answers = {str(k): float(v) for k, v in zip(keys.cid, keys.estimate, strict=True)}
    with threadpool_limits(2):
        for c in [c for c in s.comparisons if c.cid in PILOT]:
            key = answers[c.cid]
            tokens = None
            for draw in range(draws):
                d = data.with_features(one_try_copy(c, s.tries, draw), c, s)
                tokens = tokens or tokenize(d.report)
                out = cr.ladder(d, seed=draw, rungs=(0, 2, 4, 5), tokens=tokens)
                for m, r in out.items():
                    rows.append(
                        {"cid": c.cid, "draw": draw, "method": m, "error": r.estimate - key}
                    )
    d = pd.DataFrame(rows)
    return d.groupby(["cid", "method"]).error.mean().unstack("method")


def pts(x: float) -> str:
    """Format a share as signed points, e.g. 0.034 -> +3.4."""
    return f"{x * 100:+.1f}"


def write_report(
    cfg: Config, keys: pd.DataFrame, gng: pd.DataFrame, s: dict[str, Any], path: Path | None = None
) -> Path:
    """Write ``docs/one_try/06_modelling.md``."""
    lines = [
        "# Step 6: Modelling",
        "",
        "*Generated by `agent-tips onetry model`. Paper 2, the one-try study. Settings are frozen in "
        "`01_problem.md` (with amendments A1–A6).*",
        "",
        "## In plain words",
        "",
        f"- **Answer key:** for each of the {len(keys)} comparisons we worked out the many-tries answer, "
        f"with its uncertainty. The typical uncertainty (median half-width of the 95% CI) is "
        f"{s['median_noise_floor'] * 100:.1f} points, well inside the ±{s['margin'] * 100:.0f}-point margin "
        f"we use to judge the methods ({'check passed' if s['margin_ok'] else '**check failed**'}: the margin must be at least twice that).",
        "- **Methods:** seven correction methods, from a simple comparison up to machine learning "
        "with other AIs' results (the ladder below). Each was first tested on made-up data where we "
        "know the true answer; all those tests pass.",
        (
            f"- **Go/no-go:** on the pilot's four comparisons the methods repeat the pilot's pattern "
            f"(average error: simple {s['gng']['rung0'] * 100:.1f}, report-text ML "
            f"{s['gng']['rung2'] * 100:.1f}, + human fix {s['gng']['rung4'] * 100:.1f}, + other AIs "
            f"{s['gng']['rung5'] * 100:.1f} points): " + ("**go**." if s["go"] else "**no-go**.")
        )
        if s["gng"]
        else "- **Go/no-go:** not run (the pilot's comparisons are not in this data).",
        "",
        "## The correction ladder",
        "",
        "| Rung | Method | Information used |",
        "| --- | --- | --- |",
        "| 0 | Simple difference in fix rates | — |",
        "| 1 | Linear regression | Report facts |",
        "| 2 | Double machine learning (gradient boosting, 5 folds by bug) | Report facts + report text (TF-IDF → 100 numbers, fitted on training folds) |",
        "| 3 | As rung 2 (exploratory) | + language-model embeddings of the report |",
        "| 4 | As rung 2 | + size of the human fix |",
        "| 5 | As rung 2 | + other AIs' fix rate on the bug |",
        "| 6 | As rung 2 | + IRT difficulty from other AIs |",
        "| checks | Random forest (rung 5); doubly robust AIPW (rungs 2, 4, 5) | As the rung |",
        "",
        "## Tests on made-up data with a known answer",
        "",
        "| What is tested | Test |",
        "| --- | --- |",
    ]
    lines += [f"| {a} | `{b}` |" for a, b in SYNTHETIC_TESTS]
    lines += [
        "",
        "## Go/no-go: the pilot's comparisons",
        "",
        "*Average error (estimate minus answer key, points) over 5 draws.*",
        "",
        "| Comparison | Simple | Report-text ML | + human fix | + other AIs |",
        "| --- | --- | --- | --- | --- |",
    ]
    for cid, r in gng.iterrows():
        lines.append(
            f"| `{cid}` | {pts(r['rung0'])} | {pts(r['rung2'])} | {pts(r['rung4'])} | {pts(r['rung5'])} |"
        )
    lines += [
        "",
        "## Answer keys",
        "",
        "| Comparison | Kind | Key bugs | Answer (points) | 95% CI | Noise floor | Conclusion |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    concl = {1: "helps", -1: "hurts", 0: "no clear difference"}
    for row in keys.sort_values(["kind", "key_bugs"], ascending=[False, False]).to_dict(
        orient="records"
    ):
        lines.append(
            f"| `{row['cid']}` | {row['kind']} | {int(row['key_bugs']):,} | {pts(row['estimate'])} | "
            f"{pts(row['ci_lo'])} to {pts(row['ci_hi'])} | {row['noise_floor'] * 100:.1f} | {concl[int(row['conclusion'])]} |"
        )
    path = path or cfg.root / "docs" / "one_try" / "06_modelling.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return path


def run(cfg: Config, log: Callable[[str], None] = print) -> Path:
    """Answer keys, go/no-go and the Step 6 report."""
    s = data.load(cfg)
    reps = int(cfg.raw["onetry"]["bootstrap_reps"])
    keys = answer_keys(s, reps, log)
    res = cfg.path("onetry_results")
    res.mkdir(parents=True, exist_ok=True)
    keys.to_parquet(res / "answer_keys.parquet", index=False)
    log("go/no-go on the pilot comparisons")
    gng = go_no_go(s, keys)
    mean_abs = gng.abs().mean() if len(gng) else pd.Series(dtype=float)
    margin = float(cfg.raw["onetry"]["margin"])
    floor = float(np.median(keys.noise_floor))
    summary = {
        "margin": margin,
        "median_noise_floor": floor,
        "margin_ok": margin >= 2 * floor,
        "gng": {k: float(v) for k, v in mean_abs.items()},
        "go": bool(len(gng) and mean_abs["rung5"] < mean_abs["rung2"] < mean_abs["rung0"]),
    }
    (res / "modelling.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return write_report(cfg, keys, gng, summary)
