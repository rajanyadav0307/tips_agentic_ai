"""Write ``docs/07_evaluation.md`` from ``outputs/results/robustness.json``."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from agent_tips.config import Config
from agent_tips.models.report import _ai


def _pts(x: float) -> str:
    return f"{x * 100:+.1f}"


def _ci(e: dict[str, Any]) -> str:
    return f"{_pts(e['estimate'])} [{_pts(e['ci_lo'])}, {_pts(e['ci_hi'])}]"


def build(cfg: Config, out: Path | None = None) -> Path:
    """Write the evaluation report and return its path."""
    r = json.loads((cfg.path("results") / "robustness.json").read_text(encoding="utf-8"))
    margin = float(cfg.raw["analysis"]["equivalence_margin"])
    lines: list[str] = []
    add = lines.append

    b = r["p1_batches"]
    p1_all = [e["estimate"] for e in b.values()] + [r["p1_within_issue_only"]["estimate"]]
    p1_ci_hi = max(e["ci_hi"] for e in b.values())
    und = r["p1_undated"]["day"]
    loo = r["p2_leave_one_out"]
    loo_lo = min(e["ci90_lo"] for e in loo.values())
    loo_hi = max(e["ci90_hi"] for e in loo.values())
    broad = r["p2_broad_definition"]
    mis = r["p2_misclassification"]
    tip = r["p2_tipping_point"]
    cal = r["p2_removal_calibration"]
    rep = r.get("reproducibility")

    add("# Step 7: Evaluation (robustness checks)")
    add("")
    add(
        "*Generated by `agent-tips evaluate` from `outputs/results/robustness.json`. "
        "Checks follow the frozen plan `docs/01_problem_and_hypotheses.md`.*"
    )
    add("")
    add("## In plain words")
    add("")
    add(
        f"- **P1 holds up.** However the older AI's model-version batches are drawn, "
        f"reproducing first costs {_pts(max(p1_all))} to {_pts(min(p1_all))} points, and "
        f"every 95% CI stays below zero (highest upper end {_pts(p1_ci_hi)})."
    )
    add(
        f"- **Undated tries (all failures) do not change P1** unless they are placed in the "
        f"most unfavourable way possible: added back like other failures the effect is "
        f"{_pts(und['added back like other failures (median of draws)'])}; the extreme "
        f"bounds are {_pts(und['added back, worst case for the finding'])} and "
        f"{_pts(und['added back, best case for the finding'])}."
    )
    add(
        f"- **P2 holds up.** Dropping any one newer AI keeps every 90% CI inside "
        f"±{margin * 100:.0f} points ({_pts(loo_lo)} to {_pts(loo_hi)}). Counting any new file "
        f"before the fix as test first gives {_ci(broad)}."
    )
    add(
        f"- **The weakest point of P2 is NVIDIA's filtering.** If test-first tries had lost "
        f"{tip['extra_failure_share']:.0%} more hidden failures than fix-first tries, the "
        f"result would reach −{margin * 100:.0f} points. In Nebius's unfiltered data, the share "
        f"of tries such filtering would remove differs by {_pts(cal['estimate'])} points, test "
        f"first minus fix first (95% CI {_pts(cal['ci_lo'])} to {_pts(cal['ci_hi'])}). "
        + (
            "Test-first tries would be removed less often, so if anything the filter works "
            "against testing first."
            if cal["estimate"] < 0
            else "Test-first tries would be removed more often."
        )
        + (
            f" Even the upper end of that interval is below the {tip['extra_failure_share']:.0%} "
            "needed."
            if cal["ci_hi"] < tip["extra_failure_share"]
            else " The interval reaches the tipping point, so this remains a real limitation."
        )
    )
    if rep:
        add(
            "- **Reproducible:** two full runs give "
            + ("identical" if rep["identical"] else "**different**")
            + " result tables."
        )
    add("")

    add("## P1: older AI, reproduce first vs search first")
    add("")
    add("### How model-version batches are defined")
    add("")
    add("| Batch | Fair estimate (pts) [95% CI] | Issues | Groups |")
    add("| --- | --- | --- | --- |")
    for name, e in b.items():
        main = " (main)" if name == "day" else ""
        add(f"| {name}{main} | {_ci(e)} | {e['n_issues']:,} | {e['n_strata']:,} |")
    w = r["p1_within_issue_only"]
    add(f"| none (issue only, incl. undated) | {_ci(w)} | {w['n_issues']:,} | {w['n_strata']:,} |")
    add("")
    add("### Undated tries")
    add("")
    add(
        "Some older-AI tries have no evaluation time, and all of them are unresolved. "
        "They cannot be put in a batch, so the main analysis leaves them out. Here they are "
        "added back to a batch of their issue in four ways."
    )
    add("")
    add("| Scenario | Batches = day | Batches = hour |")
    add("| --- | --- | --- |")
    hour = r["p1_undated"]["hour"]
    for k in und:
        add(f"| {k} | {_pts(und[k])} | {_pts(hour[k])} |")
    add("")
    add(
        "The worst and best cases place each undated failure, one at a time, where it moves "
        "the estimate most. These are extreme bounds, not plausible values."
    )
    add("")

    add("## P2: newer AIs, test first vs fix first")
    add("")
    add("### Leave one AI out")
    add("")
    add("| AI left out | Fair estimate (pts) [95% CI] | 90% CI | Inside ±2? |")
    add("| --- | --- | --- | --- |")
    for sub, e in loo.items():
        inside = "yes" if -margin < e["ci90_lo"] and e["ci90_hi"] < margin else "no"
        add(f"| {_ai(sub)} | {_ci(e)} | {_pts(e['ci90_lo'])}, {_pts(e['ci90_hi'])} | {inside} |")
    add("")
    add("### Label errors")
    add("")
    add(
        "The labeler never calls a file a test script by mistake (precision 100%) but misses "
        "about a quarter of them (recall 73%, `docs/05_feature_report.md`). A miss can only "
        "move a try between groups if the try made a new file before its fix and had no other "
        "test script. Such tries are moved at random to *test first*:"
    )
    add("")
    add("| Tries moved | Estimate (pts), median of draws | Range over draws |")
    add("| --- | --- | --- |")
    for k, v in mis.items():
        add(f"| {k} | {_pts(v['median'])} | {_pts(v['min'])} to {_pts(v['max'])} |")
    add(f"| broad definition (all moved), with CI | {_ci(broad)} | — |")
    add("")
    add("### NVIDIA's removed tries")
    add("")
    add(
        "NVIDIA removed tries that hit the step limit or made no patch. These are hidden "
        "failures. If test-first tries lost more of them, P2 is biased in favour of testing "
        "first."
    )
    add("")
    add(
        f"- **Tipping point:** test-first tries would need {tip['extra_failure_share']:.1%} "
        f"extra hidden failures (relative to their visible count, in every issue) to move the "
        f"estimate from {_pts(tip['estimate_at_zero'])} to −{margin * 100:.0f} points."
    )
    add(
        f"- **Calibration:** in the unfiltered Nebius newer-AI data, the share of tries that "
        f"NVIDIA-style filtering would remove differs by {_ci(cal)} points (test first minus "
        f"fix first, same issue; {cal['n_issues']:,} issues). "
        "Only Nebius issues where both orders occur count, so this number is uncertain."
    )
    add("")
    cl = r.get("conditional_logit", {})
    if cl:
        add("## Cross-check: conditional logistic regression")
        add("")
        add(
            "The same comparisons as odds ratios, conditional on the group (below 1 means "
            "the tip lowers the chance of fixing the bug)."
        )
        add("")
        add("| Hypothesis | Odds ratio [95% CI] | p |")
        add("| --- | --- | --- |")
        for k, v in cl.items():
            add(
                f"| {k} | {v['odds_ratio']:.3f} [{v['ci_lo']:.3f}, {v['ci_hi']:.3f}] "
                f"| {v['p_value']:.3g} |"
            )
        add("")
    add("## Reproducibility")
    add("")
    if rep:
        add(
            f"The full analysis was run twice from scratch. Result-table hashes: "
            f"`{rep['hash_run1'][:16]}` and `{rep['hash_run2'][:16]}` → "
            + ("identical." if rep["identical"] else "**different**.")
        )
    else:
        add("Not run (`--no-repro`).")
    add("")
    path = out or cfg.root / "docs" / "07_evaluation.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
